export const getPlayerById = (id) => {
  return players.find((p) => p.id === id) || players[0];
};

export const getPlayersByTeam = (teamId) => {
  return players.filter((p) => p.teamId === teamId);
};

export const getTopScorers = () => {
  return [...players].sort((a, b) => b.goals - a.goals).slice(0, 5);
};

export const getTopPlaymakers = () => {
  return [...players].sort((a, b) => b.assists - a.assists).slice(0, 5);
};
